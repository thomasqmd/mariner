# Where each generated file lands. One list so the build script and the drift
# test cannot disagree about it.
generated_files <- function(theme) {
  dir <- file.path("inst", "quarto", "_extensions", mariner_ext_name(theme))
  list(
    # The `qmd-` prefix keeps these off Bootstrap's toes on the Sass load path;
    # see the note in R/scss.R.
    `_qmd-tokens.scss`     = list(path = file.path(dir, "_qmd-tokens.scss"),     fn = build_scss_tokens),
    `_qmd-tokens-css.scss` = list(path = file.path(dir, "_qmd-tokens-css.scss"), fn = build_css_tokens),
    `brand-preamble.tex`   = list(path = file.path(dir, "brand-preamble.tex"),   fn = build_pdf_preamble),
    `_tokens.typ`          = list(path = file.path(dir, "_tokens.typ"),          fn = build_typst_tokens),
    `brand-header.html`    = list(path = file.path(dir, "brand-header.html"),    fn = build_brand_header),
    `_extension.yml`       = list(path = file.path(dir, "_extension.yml"),       fn = build_extension_yml)
  )
}

#' Synchronize extension assets and shared partials
#'
#' Copies the shared SCSS partials, bundled fonts, logos, TeX includes and Typst
#' rules into the theme's extension directory under
#' `inst/quarto/_extensions/`, so the extension is fully self-contained once
#' scaffolded into a project by `mariner_setup_project()`.
#'
#' @param root Package source root directory.
#' @param quiet Suppress the summary message.
#' @return Invisibly returns the copied file paths.
#' @noRd
sync_extension_assets <- function(root = ".", quiet = FALSE) {
  copied <- character()

  scss_files <- list.files(file.path(root, "inst", "scss"), pattern = "\\.scss$", full.names = TRUE)
  font_files <- list.files(file.path(root, "inst", "assets", "fonts"), pattern = "\\.(ttf|txt)$", full.names = TRUE)
  tex_files  <- list.files(file.path(root, "inst", "tex"), pattern = "\\.tex$", full.names = TRUE)
  typ_files  <- list.files(file.path(root, "inst", "typst"), pattern = "\\.typ$", full.names = TRUE)
  # zoom.js only. brand-header.html is GENERATED into the same directory by
  # build_brand_header(), because it names the extension and the logo file.
  js_files   <- list.files(file.path(root, "inst", "html"), pattern = "\\.js$", full.names = TRUE)
  # Every mark, not just the ones wired up today. They are ~35 KB together, and
  # a template that reaches for the stacked lockup should not need a rebuild.
  logo_files <- list.files(file.path(root, "inst", "assets", "logos"), pattern = "\\.(png|svg)$", full.names = TRUE)

  copy_into <- function(files, dir) {
    dir.create(dir, recursive = TRUE, showWarnings = FALSE)
    for (f in files) {
      dest <- file.path(dir, basename(f))
      file.copy(f, dest, overwrite = TRUE)
      copied <<- c(copied, dest)
    }
  }

  for (theme in mariner_themes) {
    ext_dir <- file.path(root, "inst", "quarto", "_extensions", mariner_ext_name(theme))
    copy_into(c(typ_files, scss_files, tex_files, js_files), ext_dir)
    copy_into(font_files, file.path(ext_dir, "fonts"))
    copy_into(logo_files, file.path(ext_dir, "logos"))
  }

  if (!quiet) {
    cli::cli_alert_success("synchronized extension assets for {paste(mariner_themes, collapse = ', ')}")
  }
  invisible(copied)
}

#' Regenerate every derived artefact
#'
#' Writes the SCSS, CSS, LaTeX, Typst and extension-manifest files for the
#' theme, then copies the shared partials, fonts and logos into the extension
#' directory. Called by `data-raw/build-tokens.R`;
#' `tests/testthat/test-no-drift.R` calls it into a temporary directory and
#' diffs against what is committed.
#'
#' @param root Package source root.
#' @param quiet Suppress the per-file message.
#' @return The paths written, invisibly.
#' @noRd
build_tokens <- function(root = ".", quiet = FALSE) {
  written <- character()
  for (theme in mariner_themes) {
    for (spec in generated_files(theme)) {
      path <- file.path(root, spec$path)
      dir.create(dirname(path), recursive = TRUE, showWarnings = FALSE)
      # cat(), not writeLines(): the generators already end their output with a
      # newline, and writeLines() would add a second one. The drift test compares
      # bytes, so that stray byte is the difference between pass and fail.
      cat(spec$fn(theme), file = path)
      written <- c(written, path)
      if (!quiet) cli::cli_alert_success("wrote {.file {spec$path}}")
    }
  }
  sync_extension_assets(root = root, quiet = quiet)
  invisible(written)
}
